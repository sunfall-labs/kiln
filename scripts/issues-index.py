#!/usr/bin/env python3
"""Regenerate docs/issues/README.md: one row per feature, with its open and closed issue counts.

The index is a convenience for a reader, not a source of truth: every issue's own `Status:` line
is. Run it after filing or closing issues (`mise run issues-index`); nothing fails when it is stale.
"""
import collections
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "issues")
CLOSED = re.compile(r"(resolved|done|closed|complete|fixed|landed|implemented|wontfix|won.t fix|superseded|obsolete)")
STATUS = re.compile(r"\s*\**(Status|State)\**\s*:\**\s*(.+)", re.I)


def bucket(status: str) -> str:
    if CLOSED.match(status):
        return "closed"
    if "progress" in status:
        return "in progress"
    if status.startswith("ready"):
        return "ready"
    if "triage" in status:
        return "needs triage"
    return "other"


def status_of(path: str) -> str:
    with open(path, errors="replace") as handle:
        for line in handle.readlines()[:15]:
            match = STATUS.match(line)
            if match:
                return match.group(2).strip().strip("*").lower()
    return "none"


def title_of(path: str) -> str:
    with open(path, errors="replace") as handle:
        for line in handle:
            if line.startswith("# "):
                return line[2:].strip().replace("|", "\\|")
    return ""


def main() -> int:
    root = os.path.normpath(ROOT)
    rows = []
    totals = collections.Counter()
    for feature in sorted(os.listdir(root)):
        directory = os.path.join(root, feature)
        if not os.path.isdir(directory):
            continue
        counts = collections.Counter()
        issues = os.path.join(directory, "issues")
        if os.path.isdir(issues):
            for name in sorted(os.listdir(issues)):
                if name.endswith(".md"):
                    counts[bucket(status_of(os.path.join(issues, name)))] += 1
        prd = os.path.join(directory, "PRD.md")
        title = title_of(prd) if os.path.exists(prd) else ""
        totals.update(counts)
        rows.append((feature, title, counts))

    open_keys = ("in progress", "ready", "needs triage", "other")
    lines = [
        "# Issues",
        "",
        "Every feature's PRD and issues, one directory each. Conventions, and why deleting a filing",
        "is refused, are in [`docs/agents/issue-tracker.md`](../agents/issue-tracker.md). This page is",
        "generated by `scripts/issues-index.py` (`mise run issues-index`); each issue's own `Status:`",
        "line is the truth.",
        "",
        "| | in progress | ready | needs triage | other open | closed |",
        "|---|---:|---:|---:|---:|---:|",
        "| **all features** | "
        + " | ".join(str(totals[k]) for k in open_keys)
        + f" | {totals['closed']} |",
        "",
        "| feature | PRD | in progress | ready | needs triage | other open | closed |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for feature, title, counts in rows:
        cells = " | ".join(str(counts[k]) if counts[k] else "" for k in open_keys)
        closed = str(counts["closed"]) if counts["closed"] else ""
        lines.append(f"| [`{feature}`]({feature}/) | {title} | {cells} | {closed} |")
    lines.append("")
    with open(os.path.join(root, "README.md"), "w") as handle:
        handle.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
