#!/usr/bin/env bash
# Regenerates packages/kiln-types -- the TypeScript declarations for every public `kiln:` module
# and the parallel collection methods -- from the engine's own sources, so editor types cannot
# drift from the implementation. One package declares them all, as `@types/node` does for
# `node:*`; a program adds "@kiln/types" to `compilerOptions.types`.
#
# Needs a TypeScript compiler: TSC=/path/to/typescript/bin/tsc, or `npx tsc` when unset.
# `--check` fails instead of writing when a file is out of date, then type-checks the GUI
# examples and packages/kiln-types/test/usage.ts against the result.
set -euo pipefail
cd "$(dirname "$0")/.."
tsc() {
	if [[ -n "${TSC:-}" ]]; then node "$TSC" "$@"; else npx --yes -p typescript@6 tsc "$@"; fi
}
src=crates/semantics/kiln-builtins/src
package=packages/kiln-types
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/in" "$work/out" "$work/gen"

# The sources import each other by engine specifier; the compiler sees relative files.
for file in gui.ts actors.ts actors_core.ts actors_worker.ts shared.ts kiln_process.ts; do
	sed -e 's|"kiln:actors/core"|"./actors_core"|' -e 's|"kiln:actors/worker"|"./actors_worker"|' \
		"$src/$file" >"$work/in/$file"
done
# Only what the sources reach for at run time; the declarations they export never name these.
cat >"$work/in/env.d.ts" <<'ENV'
declare var process: any;
declare var console: any;
declare var kilnExtensions: boolean;
declare function setTimeout(fn: (...args: any[]) => void, ms?: number): any;
declare function setInterval(fn: () => void, ms?: number): any;
declare function clearInterval(id: any): void;
declare function queueMicrotask(fn: () => void): void;
declare function structuredClone<T>(value: T): T;
declare function __kilnHostProcessStart(frame: Uint8Array): any;
declare function __kilnHostProcessCancel(id: any): void;
declare class TextDecoder { decode(b: Uint8Array): string }
declare class TextEncoder { encode(s: string): Uint8Array }
declare class URL { readonly href: string; constructor(url: string, base?: string | URL) }
declare class DOMException extends Error { constructor(message?: string, name?: string) }
declare class AbortSignal {
  readonly aborted: boolean;
  readonly reason: any;
  addEventListener(type: string, listener: (...args: any[]) => void, options?: any): void;
  removeEventListener(type: string, listener: (...args: any[]) => void): void;
}
declare module "node:worker_threads" {
  export const Worker: any, MessageChannel: any, MessagePort: any;
  export const isMainThread: boolean, parentPort: any, workerData: any;
  export type MessagePort = any;
}
ENV
tsc --strict --target es2022 --lib es2022 --declaration --emitDeclarationOnly --stripInternal \
	--skipLibCheck --outDir "$work/out" "$work/in"/*.ts

header() {
	echo "// Generated by scripts/gen-kiln-types.sh from crates/semantics/kiln-builtins/src/$1."
	echo "// Do not edit by hand."
	echo
}
# A module's emitted declarations as the body of `declare module "<name>"`.
body() {
	sed -e 's/^declare //' -e 's/^export declare /export /' -e 's/^/  /' -e 's/^  $//' "$@" |
		grep -v '^  export {};$' |
		grep -v '^  import .* from "\./actors_core";$' |
		grep -v '^  export \(type \)\?{[^}]*} from "\./actors_core";$'
}

{
	header gui.ts
	echo 'declare module "kiln:gui" {'
	body "$work/out/gui.d.ts"
	echo '}'
	cat <<'JSX'

declare module "kiln:gui/jsx-runtime" {
  import type * as gui from "kiln:gui";
  export { jsx, jsxs, jsxDEV, Fragment } from "kiln:gui";

  type PropsOf<C extends abstract new (...args: any) => any> = Exclude<
    ConstructorParameters<C>[0],
    string | ((...args: any[]) => any) | undefined
  >;

  export namespace JSX {
    /** Components return elements, widgets, text or accessors; all are valid children. */
    type Element = any;
    type ElementClass = gui.Node;
    interface ElementAttributesProperty {}
    interface ElementChildrenAttribute {
      children: {};
    }
    interface IntrinsicAttributes {
      key?: string | number;
    }
    interface IntrinsicElements {
      window: gui.WindowProps;
      vstack: gui.ContainerProps;
      hstack: gui.ContainerProps;
      box: PropsOf<typeof gui.Box>;
      grid: gui.GridProps;
      card: PropsOf<typeof gui.Card>;
      scroll: gui.ContainerProps;
      text: PropsOf<typeof gui.Text>;
      button: gui.ButtonProps;
      input: gui.TextInputProps;
      textarea: PropsOf<typeof gui.TextArea>;
      slider: PropsOf<typeof gui.Slider>;
      toggle: PropsOf<typeof gui.Toggle>;
      checkbox: PropsOf<typeof gui.Checkbox>;
      select: gui.ChoiceProps;
      segmented: gui.ChoiceProps;
      progress: PropsOf<typeof gui.ProgressBar>;
      spinner: gui.LayoutProps;
      image: PropsOf<typeof gui.Image>;
      divider: gui.LayoutProps;
      spacer: gui.LayoutProps;
    }
  }
}

declare module "kiln:gui/jsx-dev-runtime" {
  export * from "kiln:gui/jsx-runtime";
}
JSX
} >"$work/gen/gui.d.ts"

# `kiln:actors` is two engine files, one public module: the shared core's public half (its
# internal exports are `@internal` and stripped) and the actor API that re-exports it.
{
	header "actors.ts and actors_core.ts"
	echo 'declare module "kiln:actors" {'
	body "$work/out/actors_core.d.ts"
	body "$work/out/actors.d.ts"
	echo '}'
} >"$work/gen/actors.d.ts"

{
	header shared.ts
	echo 'declare module "kiln:shared" {'
	body "$work/out/shared.d.ts"
	echo '}'
} >"$work/gen/shared.d.ts"

{
	header kiln_process.ts
	echo 'declare module "kiln:process" {'
	body "$work/out/kiln_process.d.ts"
	echo '}'
} >"$work/gen/process.d.ts"

# The parallel family is installed by property definition (parallel.ts, typedarray.ts), which
# carries no static types: its signatures are written here, beside the meaning parallel.ts gives
# them. `--check` holds the method list to the engine's extension registry.
cat >"$work/gen/parallel.d.ts" <<'PARALLEL'
// Generated by scripts/gen-kiln-types.sh; signatures of the parallel collection methods
// (crates/semantics/kiln-builtins/src/parallel.ts, ADR 0069). Do not edit by hand.
//
// Each is its sequential counterpart's meaning, run across cores where the engine proves the
// callback pure. `parallelReduce` folds fixed leaves from `initial` and combines them pairwise:
// `initial` should be an identity of `combine`, and `combine` associative.

interface Array<T> {
  parallelMap<U>(callback: (value: T, index: number, array: T[]) => U, thisArg?: any): U[];
  parallelFilter<S extends T>(predicate: (value: T, index: number, array: T[]) => value is S, thisArg?: any): S[];
  parallelFilter(predicate: (value: T, index: number, array: T[]) => unknown, thisArg?: any): T[];
  parallelFlatMap<U>(callback: (value: T, index: number, array: T[]) => U | ReadonlyArray<U>, thisArg?: any): U[];
  parallelSort(compareFn?: (a: T, b: T) => number): this;
  parallelReduce<A>(callback: (accumulator: A, value: T, index: number, array: T[]) => A, combine: (left: A, right: A) => A, initial: A): A;
}

interface ReadonlyArray<T> {
  parallelMap<U>(callback: (value: T, index: number, array: readonly T[]) => U, thisArg?: any): U[];
  parallelFilter<S extends T>(predicate: (value: T, index: number, array: readonly T[]) => value is S, thisArg?: any): S[];
  parallelFilter(predicate: (value: T, index: number, array: readonly T[]) => unknown, thisArg?: any): T[];
  parallelFlatMap<U>(callback: (value: T, index: number, array: readonly T[]) => U | ReadonlyArray<U>, thisArg?: any): U[];
  parallelReduce<A>(callback: (accumulator: A, value: T, index: number, array: readonly T[]) => A, combine: (left: A, right: A) => A, initial: A): A;
}
PARALLEL
for typed in Int8Array Uint8Array Uint8ClampedArray Int16Array Uint16Array Int32Array Uint32Array \
	Float32Array Float64Array; do
	cat >>"$work/gen/parallel.d.ts" <<TYPED

interface $typed {
  parallelMap(callback: (value: number, index: number, array: this) => number, thisArg?: any): $typed;
  parallelFilter(predicate: (value: number, index: number, array: this) => unknown, thisArg?: any): $typed;
  parallelSort(compareFn?: (a: number, b: number) => number): this;
  parallelReduce<A>(callback: (accumulator: A, value: number, index: number, array: this) => A, combine: (left: A, right: A) => A, initial: A): A;
}
TYPED
done
for typed in BigInt64Array BigUint64Array; do
	cat >>"$work/gen/parallel.d.ts" <<TYPED

interface $typed {
  parallelMap(callback: (value: bigint, index: number, array: this) => bigint, thisArg?: any): $typed;
  parallelFilter(predicate: (value: bigint, index: number, array: this) => unknown, thisArg?: any): $typed;
  parallelSort(compareFn?: (a: bigint, b: bigint) => number | bigint): this;
  parallelReduce<A>(callback: (accumulator: A, value: bigint, index: number, array: this) => A, combine: (left: A, right: A) => A, initial: A): A;
}
TYPED
done

files=(gui.d.ts actors.d.ts shared.d.ts process.d.ts parallel.d.ts)
if [[ "${1:-}" == "--check" ]]; then
	stale=0
	for file in "${files[@]}"; do
		diff -u "$package/$file" "$work/gen/$file" || stale=1
	done
	if [[ $stale -ne 0 ]]; then
		echo "gen-kiln-types: $package is out of date; run scripts/gen-kiln-types.sh" >&2
		exit 1
	fi
	# Every parallel method the engine declares (`KILN_EXTENSIONS`, the one registry of kiln's
	# additions to built-ins) is declared here, and nothing else is.
	installed="$(sed -n '/^pub const KILN_EXTENSIONS/,/^];/p' crates/semantics/kiln-builtin-surface/src/lib.rs |
		grep -o 'MemberKey::Named("parallel[A-Za-z]*")' | grep -o 'parallel[A-Za-z]*' | sort -u)"
	declared="$(grep -o '^  parallel[A-Za-z]*' "$package/parallel.d.ts" | tr -d ' ' | sort -u)"
	if [[ "$installed" != "$declared" ]]; then
		echo "gen-kiln-types: parallel.d.ts declares [$(echo $declared)] but the engine installs [$(echo $installed)]" >&2
		exit 1
	fi
	cat >"$work/process-env.d.ts" <<'ENV'
declare var process: any;
ENV
	cat >"$work/tsconfig.json" <<CONF
{ "compilerOptions": { "strict": true, "noEmit": true, "target": "es2022", "lib": ["es2022", "dom"],
  "module": "esnext", "moduleResolution": "bundler", "jsx": "react-jsx", "jsxImportSource": "kiln:gui",
  "types": [] },
  "files": ["$PWD/$package/index.d.ts", "$work/process-env.d.ts", "$PWD/$package/test/usage.ts",
    "$PWD/examples/gui-counter.tsx", "$PWD/examples/gui-todo.tsx", "$PWD/examples/gui-studio.tsx",
    "$PWD/conformance/gui/native-smoke.tsx"] }
CONF
	tsc -p "$work/tsconfig.json"
	echo "gen-kiln-types: declarations current; usage and GUI examples type-check"
else
	for file in "${files[@]}"; do cp "$work/gen/$file" "$package/$file"; done
	echo "gen-kiln-types: wrote ${files[*]/#/$package/}"
fi
