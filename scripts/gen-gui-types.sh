#!/usr/bin/env bash
# Regenerates packages/kiln-gui/gui.d.ts from the kiln:gui source, so editor types cannot drift
# from the implementation. Needs a TypeScript compiler: TSC=/path/to/typescript/bin/tsc, or
# `npx tsc` when unset. `--check` fails instead of writing when the file is out of date, and
# also type-checks the GUI examples against the result.
set -euo pipefail
cd "$(dirname "$0")/.."
tsc() {
	if [[ -n "${TSC:-}" ]]; then node "$TSC" "$@"; else npx --yes -p typescript@6 tsc "$@"; fi
}
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cp crates/semantics/kiln-builtins/src/gui.ts "$work/gui.ts"
cat >"$work/env.d.ts" <<'ENV'
declare var process: any;
declare var console: any;
declare function setTimeout(fn: () => void, ms?: number): any;
declare function queueMicrotask(fn: () => void): void;
declare function setInterval(fn: () => void, ms?: number): any;
declare function clearInterval(id: any): void;
declare class TextDecoder { decode(b: Uint8Array): string }
ENV
tsc --strict --target es2022 --lib es2022 --declaration --emitDeclarationOnly --outDir "$work/out" "$work/gui.ts" "$work/env.d.ts"
{
	echo "// Generated by scripts/gen-gui-types.sh from crates/semantics/kiln-builtins/src/gui.ts."
	echo "// Do not edit by hand."
	echo
	echo 'declare module "kiln:gui" {'
	sed -e 's/^declare //' -e 's/^export declare /export /' -e 's/^/  /' -e 's/^  $//' "$work/out/gui.d.ts" | grep -v '^  export {};$'
	echo '}'
	cat <<'JSX'

declare module "kiln:gui/jsx-runtime" {
  import type * as gui from "kiln:gui";
  export { jsx, jsxs, jsxDEV, Fragment } from "kiln:gui";

  type PropsOf<C extends abstract new (...args: any) => any> = Exclude<
    ConstructorParameters<C>[0],
    string | ((...args: any[]) => any) | undefined
  >;

  export namespace JSX {
    /** Components return elements, widgets, text or accessors; all are valid children. */
    type Element = any;
    type ElementClass = gui.Node;
    interface ElementAttributesProperty {}
    interface ElementChildrenAttribute {
      children: {};
    }
    interface IntrinsicAttributes {
      key?: string | number;
    }
    interface IntrinsicElements {
      window: gui.WindowProps;
      vstack: gui.ContainerProps;
      hstack: gui.ContainerProps;
      box: PropsOf<typeof gui.Box>;
      grid: gui.GridProps;
      card: PropsOf<typeof gui.Card>;
      scroll: gui.ContainerProps;
      text: PropsOf<typeof gui.Text>;
      button: gui.ButtonProps;
      input: gui.TextInputProps;
      textarea: PropsOf<typeof gui.TextArea>;
      slider: PropsOf<typeof gui.Slider>;
      toggle: PropsOf<typeof gui.Toggle>;
      checkbox: PropsOf<typeof gui.Checkbox>;
      select: gui.ChoiceProps;
      segmented: gui.ChoiceProps;
      progress: PropsOf<typeof gui.ProgressBar>;
      spinner: gui.LayoutProps;
      image: PropsOf<typeof gui.Image>;
      divider: gui.LayoutProps;
      spacer: gui.LayoutProps;
    }
  }
}

declare module "kiln:gui/jsx-dev-runtime" {
  export * from "kiln:gui/jsx-runtime";
}
JSX
} >"$work/gui.d.ts"
target=packages/kiln-gui/gui.d.ts
if [[ "${1:-}" == "--check" ]]; then
	diff -u "$target" "$work/gui.d.ts" || { echo "gen-gui-types: $target is out of date; run scripts/gen-gui-types.sh" >&2; exit 1; }
	cat >"$work/tsconfig.json" <<CONF
{ "compilerOptions": { "strict": true, "noEmit": true, "target": "es2022", "lib": ["es2022"],
  "module": "esnext", "moduleResolution": "bundler", "jsx": "react-jsx", "jsxImportSource": "kiln:gui",
  "types": [] },
  "files": ["$PWD/$target", "$work/env.d.ts", "$PWD/examples/gui-counter.tsx", "$PWD/examples/gui-todo.tsx",
    "$PWD/examples/gui-studio.tsx", "$PWD/conformance/gui/native-smoke.tsx"] }
CONF
	tsc -p "$work/tsconfig.json"
	echo "gen-gui-types: declarations current; examples type-check"
else
	cp "$work/gui.d.ts" "$target"
	echo "gen-gui-types: wrote $target"
fi
