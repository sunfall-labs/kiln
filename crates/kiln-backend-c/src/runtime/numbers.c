/* `Number::toString` in base ten: the shortest decimal that reads back as the same double,
 * spelled the way the language spells it (ECMA-262 6.1.6.1.20).
 *
 * This is the answer for every number the runtime turns into text -- `String(x)`, a template
 * literal, a concatenation, an object key, `JSON.stringify` -- and it used to be a call across
 * the FFI into the Rust provider with a boundary struct each way. Profiled on
 * `bench/non-io/json.mjs` that call was the largest single cost of writing a document.
 *
 * The shortest-digits problem is not "print seventeen digits and trim": the digit string has to
 * be the *least* number of digits k that still parses back to this exact double, and among the
 * candidates with that k, the nearest one, ties to even. Grisu2 gets that wrong for some inputs
 * (it is shortest only most of the time, with no way to know which time this is) and Grisu3 has
 * to fall back to a bignum. Ryu (Adams, PLDI 2018) is exact by construction, which is what the
 * differential probe `conformance/native/number-to-string-fuzz.js` asserts against node over
 * 200,000 bit patterns: it decides the question in fixed-width integer arithmetic, by carrying
 * the two halfway bounds of the rounding interval alongside the value and stripping digits
 * until the bounds separate.
 *
 * The two multiplier tables live in `runtime/ryu_tables.c`, generated by
 * `scripts/gen-ryu-tables.py`; the tables are data and the code below is not a transcription of
 * anyone's. */

/* floor(log10(2^e)), exact for e in [0, 1650]; the generator asserts the range. */
static uint32_t kiln_c99_ryu_log10_pow2(uint32_t e) { return (e * UINT32_C(78913)) >> 18; }

/* floor(log10(5^e)), exact for e in [0, 2620]. */
static uint32_t kiln_c99_ryu_log10_pow5(uint32_t e) { return (e * UINT32_C(732923)) >> 20; }

/* The bit length of 5^e, exact for e in [0, 3528]. */
static uint32_t kiln_c99_ryu_pow5_bits(uint32_t e) { return ((e * UINT32_C(1217359)) >> 19) + 1; }

/* floor(m * multiplier / 2^shift), where `multiplier` is a 128-bit table entry held as
 * {low, high}. The product is 192 bits wide; the bottom 64 are dropped before the shift because
 * `shift` is always at least 64 here -- that is what the table's 125-bit normalisation buys, and
 * the discarded bits cannot reach the result. */
static uint64_t kiln_c99_ryu_mul_shift(uint64_t m, const uint64_t *multiplier, int32_t shift) {
    unsigned __int128 low = (unsigned __int128)m * multiplier[0];
    unsigned __int128 high = (unsigned __int128)m * multiplier[1];
    return (uint64_t)(((low >> 64) + high) >> (shift - 64));
}

/* How many factors of five divide `value`, which must not be zero.
 *
 * Multiplying by the modular inverse of five is a permutation of the 64-bit words that maps the
 * multiples of 5 onto the low fifth of the range, so a value with k factors of five lands below
 * 2^64/5 exactly k times before it stops. That is a shift and a multiply per factor instead of a
 * division. */
static uint32_t kiln_c99_ryu_pow5_factor(uint64_t value) {
    const uint64_t inverse_of_five = UINT64_C(14757395258967641293);
    const uint64_t one_fifth = UINT64_C(3689348814741910323);
    uint32_t count = 0;
    for (;;) {
        value *= inverse_of_five;
        if (value > one_fifth) {
            return count;
        }
        ++count;
    }
}

/* The shortest round-tripping decimal for the *finite, non-zero* magnitude whose bits are
 * `bits`: returns the digits as an integer and writes the power of ten they are scaled by, so
 * that the value is `result * 10^*exponent`. */
static uint64_t kiln_c99_ryu_shortest(uint64_t bits, int32_t *exponent) {
    uint64_t ieee_mantissa = bits & ((UINT64_C(1) << 52) - 1);
    uint32_t ieee_exponent = (uint32_t)((bits >> 52) & UINT32_C(0x7FF));
    int32_t e2;
    uint64_t m2;
    int accept_bounds;
    uint64_t mv;
    uint32_t mm_shift;
    uint64_t vr;
    uint64_t vp;
    uint64_t vm;
    int32_t e10;
    int vm_trailing_zeros = 0;
    int vr_trailing_zeros = 0;
    uint32_t removed = 0;
    uint32_t last_removed = 0;
    uint64_t output;

    /* The value is `m2 * 2^e2`, with two extra bits of headroom (`4 *` below) so that the two
     * halfway points of the rounding interval -- the boundaries beyond which a reader would
     * choose a different double -- are integers in the same scale. */
    if (ieee_exponent == 0) {
        e2 = 1 - 1023 - 52 - 2;
        m2 = ieee_mantissa;
    } else {
        e2 = (int32_t)ieee_exponent - 1023 - 52 - 2;
        m2 = (UINT64_C(1) << 52) | ieee_mantissa;
    }
    /* An even mantissa owns its boundaries: round-to-even means a decimal sitting exactly on one
     * still reads back as this double, so the interval is closed and one more digit can go. */
    accept_bounds = (m2 & 1) == 0;
    mv = 4 * m2;
    /* The interval is asymmetric at a power of two, where the neighbour below is half a step
     * closer than the neighbour above. */
    mm_shift = (ieee_mantissa != 0 || ieee_exponent <= 1) ? UINT32_C(1) : UINT32_C(0);

    /* Move the value and its two bounds into a decimal scale, by one 64x128 multiply each. The
     * exponent decides which table answers: a positive binary exponent divides by a power of ten
     * (the reciprocal table), a negative one multiplies by a power of five. */
    if (e2 >= 0) {
        uint32_t q = kiln_c99_ryu_log10_pow2((uint32_t)e2) - (e2 > 3 ? UINT32_C(1) : UINT32_C(0));
        int32_t bits_of_five = (int32_t)kiln_c99_ryu_pow5_bits(q);
        int32_t shift = -e2 + (int32_t)q + 125 + bits_of_five - 1;
        const uint64_t *multiplier = kiln_c99_ryu_pow5_inv[q];
        vr = kiln_c99_ryu_mul_shift(mv, multiplier, shift);
        vp = kiln_c99_ryu_mul_shift(mv + 2, multiplier, shift);
        vm = kiln_c99_ryu_mul_shift(mv - 1 - mm_shift, multiplier, shift);
        e10 = (int32_t)q;
        /* Whether the scaled value or its lower bound is *exactly* representable -- which is
         * what lets a digit be dropped rather than rounded. Above q = 21 a 53-bit significand
         * cannot carry that many factors of five, so the question does not arise. */
        if (q <= 21) {
            if (mv % 5 == 0) {
                vr_trailing_zeros = kiln_c99_ryu_pow5_factor(mv) >= q;
            } else if (accept_bounds) {
                vm_trailing_zeros = kiln_c99_ryu_pow5_factor(mv - 1 - mm_shift) >= q;
            } else if (kiln_c99_ryu_pow5_factor(mv + 2) >= q) {
                vp -= 1;
            }
        }
    } else {
        uint32_t q =
            kiln_c99_ryu_log10_pow5((uint32_t)(-e2)) - (-e2 > 1 ? UINT32_C(1) : UINT32_C(0));
        int32_t index = -e2 - (int32_t)q;
        int32_t shift = (int32_t)q - ((int32_t)kiln_c99_ryu_pow5_bits((uint32_t)index) - 125);
        const uint64_t *multiplier = kiln_c99_ryu_pow5[index];
        vr = kiln_c99_ryu_mul_shift(mv, multiplier, shift);
        vp = kiln_c99_ryu_mul_shift(mv + 2, multiplier, shift);
        vm = kiln_c99_ryu_mul_shift(mv - 1 - mm_shift, multiplier, shift);
        e10 = (int32_t)q + e2;
        if (q <= 1) {
            /* Multiplying by 5^0 or 5^1 keeps every bit, so the scaled value is exact. */
            vr_trailing_zeros = 1;
            if (accept_bounds) {
                vm_trailing_zeros = mm_shift == 1;
            } else {
                vp -= 1;
            }
        } else if (q < 63) {
            vr_trailing_zeros = (mv & ((UINT64_C(1) << q) - 1)) == 0;
        }
    }

    /* Strip decimal digits while the two bounds still disagree: the moment `vp` and `vm` round
     * to the same digit string there is nothing left to distinguish this double from its
     * neighbour, and the previous string was the shortest one that does. */
    if (vm_trailing_zeros || vr_trailing_zeros) {
        /* The rare branch (about 0.7% of doubles): an exactly-representable bound has to be
         * tracked digit by digit, because a bound that is exactly on the boundary is only
         * usable when the digits below it really were zero. */
        for (;;) {
            uint64_t vp_over_ten = vp / 10;
            uint64_t vm_over_ten = vm / 10;
            uint64_t vr_over_ten;
            if (vp_over_ten <= vm_over_ten) {
                break;
            }
            vr_over_ten = vr / 10;
            vm_trailing_zeros = vm_trailing_zeros && vm - 10 * vm_over_ten == 0;
            vr_trailing_zeros = vr_trailing_zeros && last_removed == 0;
            last_removed = (uint32_t)(vr - 10 * vr_over_ten);
            vr = vr_over_ten;
            vp = vp_over_ten;
            vm = vm_over_ten;
            ++removed;
        }
        if (vm_trailing_zeros) {
            for (;;) {
                uint64_t vm_over_ten = vm / 10;
                uint64_t vr_over_ten;
                if (vm - 10 * vm_over_ten != 0) {
                    break;
                }
                vr_over_ten = vr / 10;
                vr_trailing_zeros = vr_trailing_zeros && last_removed == 0;
                last_removed = (uint32_t)(vr - 10 * vr_over_ten);
                vr = vr_over_ten;
                vp = vp / 10;
                vm = vm_over_ten;
                ++removed;
            }
        }
        /* An exact ...50...0 is the tie the language breaks towards the even digit. */
        if (vr_trailing_zeros && last_removed == 5 && vr % 2 == 0) {
            last_removed = 4;
        }
        output = vr + ((vr == vm && (!accept_bounds || !vm_trailing_zeros)) || last_removed >= 5);
    } else {
        int round_up = 0;
        uint64_t vp_over_hundred = vp / 100;
        uint64_t vm_over_hundred = vm / 100;
        /* Two digits at a time first: the bounds are far enough apart to lose both for about
         * 86% of the doubles that reach here, and a 64-bit division is not cheap. */
        if (vp_over_hundred > vm_over_hundred) {
            uint64_t vr_over_hundred = vr / 100;
            round_up = vr - 100 * vr_over_hundred >= 50;
            vr = vr_over_hundred;
            vp = vp_over_hundred;
            vm = vm_over_hundred;
            removed += 2;
        }
        for (;;) {
            uint64_t vp_over_ten = vp / 10;
            uint64_t vm_over_ten = vm / 10;
            uint64_t vr_over_ten;
            if (vp_over_ten <= vm_over_ten) {
                break;
            }
            vr_over_ten = vr / 10;
            round_up = vr - 10 * vr_over_ten >= 5;
            vr = vr_over_ten;
            vp = vp_over_ten;
            vm = vm_over_ten;
            ++removed;
        }
        output = vr + (vr == vm || round_up);
    }
    *exponent = e10 + (int32_t)removed;
    return output;
}

/* The JavaScript spelling of `value`, written into `out` and returned as a length. Never more
 * than 26 bytes: the widest answer is a sign, `0.`, six zeros and seventeen digits.
 *
 * The layout rules are ECMA-262 6.1.6.1.20 steps 5 through 10 read literally, over the digit
 * string `s` of length `k` and the position `n` of the decimal point. They are the reason a
 * `%.17g` from the C library cannot stand in -- besides its answering to the process locale,
 * which is the whole reason nothing here reaches for stdio: the language switches to exponential
 * notation at thresholds of its own (21 digits above, six zeros below), spells the exponent with
 * a sign and no leading zeros, and drops the point entirely for a single digit.
 *
 * The answer is the returned length and nothing else: `out` is not NUL-terminated, and the byte
 * past the answer is left as it was. Every caller passes the length on; none may call `strlen`
 * on the buffer. (The provider call this replaced did terminate, and wanted room for it.) */
static size_t kiln_c99_double_to_js(double value, char out[32]) {
    uint64_t bits;
    int negative;
    uint64_t ieee_mantissa;
    uint32_t ieee_exponent;
    uint64_t output;
    int32_t exponent;
    char digit_buf[24];
    char *digits;
    size_t k;
    int32_t n;
    size_t length = 0;

    memcpy(&bits, &value, sizeof bits);
    negative = (int)(bits >> 63);
    ieee_mantissa = bits & ((UINT64_C(1) << 52) - 1);
    ieee_exponent = (uint32_t)((bits >> 52) & UINT32_C(0x7FF));

    if (ieee_exponent == UINT32_C(0x7FF)) {
        if (ieee_mantissa != 0) {
            memcpy(out, "NaN", 3);
            return 3;
        }
        if (negative) {
            memcpy(out, "-Infinity", 9);
            return 9;
        }
        memcpy(out, "Infinity", 8);
        return 8;
    }
    /* Both zeros spell "0": `String(-0)` is "0", and this is the one place the sign is dropped
     * rather than carried, so it has to come before the sign is written below. */
    if (ieee_exponent == 0 && ieee_mantissa == 0) {
        out[0] = '0';
        return 1;
    }

    {
        /* An integer under 2^53 is its own shortest decimal -- every one of them is a distinct
         * double, so there is no interval to search and no rounding question to ask. This is the
         * common case at nearly every call site: an array index being spelled as an object key,
         * a counter, an id. It joins the general path at the layout below with `exponent` zero,
         * where `k <= n <= 21` writes the digits out as they stand. */
        double magnitude = negative ? -value : value;
        if (magnitude < 9007199254740992.0) {
            uint64_t integral = (uint64_t)magnitude;
            if ((double)integral == magnitude) {
                output = integral;
                exponent = 0;
            } else {
                output = kiln_c99_ryu_shortest(bits & ~(UINT64_C(1) << 63), &exponent);
            }
        } else {
            output = kiln_c99_ryu_shortest(bits & ~(UINT64_C(1) << 63), &exponent);
        }
    }

    /* The digits, written from the least significant backwards into the end of the buffer, so
     * `digits` simply points at the first one and the reversal pass this used to make is gone.
     * A shortest decimal is at most seventeen digits and nearly always fewer than ten, so the
     * common case divides a 32-bit value -- which on this platform is a multiply and a shift
     * where the 64-bit division was a wider multiply, a subtract and a second multiply. */
    {
        char *tail = digit_buf + sizeof digit_buf;
        if (output <= UINT32_C(0xFFFFFFFF)) {
            uint32_t small = (uint32_t)output;
            do {
                *--tail = (char)('0' + (int)(small % 10u));
                small /= 10u;
            } while (small != 0);
        } else {
            do {
                *--tail = (char)('0' + (int)(output % 10));
                output /= 10;
            } while (output != 0);
        }
        digits = tail;
        k = (size_t)((digit_buf + sizeof digit_buf) - tail);
    }
    n = exponent + (int32_t)k;

    if (negative) {
        out[length++] = '-';
    }
    if ((int32_t)k <= n && n <= 21) {
        memcpy(out + length, digits, k);
        length += k;
        memset(out + length, '0', (size_t)(n - (int32_t)k));
        length += (size_t)(n - (int32_t)k);
    } else if (0 < n && n <= 21) {
        memcpy(out + length, digits, (size_t)n);
        length += (size_t)n;
        out[length++] = '.';
        memcpy(out + length, digits + n, k - (size_t)n);
        length += k - (size_t)n;
    } else if (-6 < n && n <= 0) {
        out[length++] = '0';
        out[length++] = '.';
        memset(out + length, '0', (size_t)(-n));
        length += (size_t)(-n);
        memcpy(out + length, digits, k);
        length += k;
    } else {
        int32_t power = n - 1;
        uint32_t magnitude = (uint32_t)(power < 0 ? -power : power);
        out[length++] = digits[0];
        if (k > 1) {
            out[length++] = '.';
            memcpy(out + length, digits + 1, k - 1);
            length += k - 1;
        }
        out[length++] = 'e';
        out[length++] = power < 0 ? '-' : '+';
        if (magnitude >= 100) {
            out[length++] = (char)('0' + (int)(magnitude / 100));
        }
        if (magnitude >= 10) {
            out[length++] = (char)('0' + (int)((magnitude / 10) % 10));
        }
        out[length++] = (char)('0' + (int)(magnitude % 10));
    }
    return length;
}

/* The exact decimal expansion of `value`'s magnitude, little-endian: `digits[0]` is the least
 * significant, and `*fractional` of them sit below the decimal point. Returns the digit count.
 *
 * Shared by the three renderings that have to round -- `toFixed`, `toExponential`,
 * `toPrecision` -- because all three must round on the value's *own* digits. That is the whole
 * argument of the comment above: scale by a power of ten first and the deciding digit is gone
 * before the language ever looks at it. Writing the expansion once means the three cannot come
 * to different conclusions about the same double.
 *
 * `value` must be finite; the callers answer the infinities and NaN from `ToString` instead. */
static size_t kiln_c99_exact_digits(double value, unsigned char *digits, size_t capacity,
                                    size_t *fractional) {
    size_t count = 0;
    size_t index;
    double mantissa;
    uint64_t scaled;
    int exponent;
    mantissa = frexp(fabs(value), &exponent);
    scaled = (uint64_t)ldexp(mantissa, 53);
    exponent -= 53;
    while (scaled != 0 && count < capacity) {
        digits[count++] = (unsigned char)(scaled % 10u);
        scaled /= 10u;
    }
    if (count == 0) {
        digits[count++] = 0;
    }
    if (exponent >= 0) {
        int step;
        for (step = 0; step < exponent; ++step) {
            unsigned carry = 0;
            for (index = 0; index < count; ++index) {
                unsigned product = (unsigned)digits[index] * 2u + carry;
                digits[index] = (unsigned char)(product % 10u);
                carry = product / 10u;
            }
            while (carry != 0 && count < capacity) {
                digits[count++] = (unsigned char)(carry % 10u);
                carry /= 10u;
            }
        }
        *fractional = 0;
    } else {
        int step;
        for (step = 0; step < -exponent; ++step) {
            unsigned carry = 0;
            for (index = 0; index < count; ++index) {
                unsigned product = (unsigned)digits[index] * 5u + carry;
                digits[index] = (unsigned char)(product % 10u);
                carry = product / 10u;
            }
            while (carry != 0 && count < capacity) {
                digits[count++] = (unsigned char)(carry % 10u);
                carry /= 10u;
            }
        }
        *fractional = (size_t)(-exponent);
    }
    /* Pad so there is a digit at every place the answer names, above the point and below it. */
    while (count < *fractional + 1 && count < capacity) {
        digits[count++] = 0;
    }
    return count;
}

static int kiln_c99_to_fixed(kiln_value *out, double value, int places) {
    /* Little-endian decimal digits: `digits[0]` is the least significant. */
    unsigned char digits[1200];
    size_t count;
    size_t fractional;
    size_t index;
    kiln_text text = {NULL, 0, 0};
    int negative = value < 0.0;
    int round_up;
    if (!isfinite(value) || fabs(value) >= 1e21) {
        *out = kiln_c99_text(kiln_c99_number(value));
        return out->tag == KILN_VALUE_STRING ? KILN_C99_OK : KILN_C99_OUT_OF_MEMORY;
    }
    count = kiln_c99_exact_digits(value, digits, sizeof digits, &fractional);
    if (fractional <= (size_t)places) {
        round_up = 0;
    } else {
        /* Round half *up*: "if there are two such n, pick the larger n". Only the deciding digit
         * is consulted, because at or above five the answer is up whatever follows. */
        round_up = digits[fractional - (size_t)places - 1] >= 5;
        for (index = 0; index < fractional - (size_t)places; ++index) {
            digits[index] = 0;
        }
        memmove(digits, digits + (fractional - (size_t)places),
                count - (fractional - (size_t)places));
        count -= fractional - (size_t)places;
        fractional = (size_t)places;
    }
    while (fractional < (size_t)places && count < sizeof digits) {
        /* The value terminated above the requested precision, so the rest is zeros. */
        memmove(digits + 1, digits, count);
        digits[0] = 0;
        count += 1;
        fractional += 1;
    }
    if (round_up) {
        for (index = 0; index < count; ++index) {
            if (digits[index] == 9) {
                digits[index] = 0;
                continue;
            }
            digits[index] += 1;
            break;
        }
        if (index == count && count < sizeof digits) {
            digits[count++] = 1;
        }
    }
    while (count > fractional + 1 && digits[count - 1] == 0) {
        /* A leading zero above the point is not part of the spelling, but the one before the
         * point is: `.5` is `0.5`. */
        count -= 1;
    }
    /* The sign survives rounding: `(-0.0004).toFixed(2)` is `"-0.00"`, which says the value was
     * negative rather than that it was nonzero. Negative zero is not negative here, so
     * `(-0).toFixed(2)` is `"0.00"`. */
    if (negative && kiln_c99_text_append_c(&text, "-") != KILN_C99_OK) {
        free(text.bytes);
        return KILN_C99_OUT_OF_MEMORY;
    }
    for (index = count; index > 0; --index) {
        char character = (char)('0' + digits[index - 1]);
        if (index == fractional && kiln_c99_text_append_c(&text, ".") != KILN_C99_OK) {
            free(text.bytes);
            return KILN_C99_OUT_OF_MEMORY;
        }
        if (kiln_c99_text_append(&text, &character, 1) != KILN_C99_OK) {
            free(text.bytes);
            return KILN_C99_OUT_OF_MEMORY;
        }
    }
    *out = kiln_c99_text_value(&text);
    return KILN_C99_OK;
}

/* The `n` and `e` the specification's exponential formats name, for a finite value.
 *
 * `count` significant digits of the *exact* expansion of the magnitude, rounded half up -- "if
 * there are two such sets, pick the larger n" -- written most significant first into `mantissa`
 * and NUL terminated, and the decimal exponent of the first of them in `*exponent`. `mantissa`
 * must have room for `count + 1` bytes. */
static void kiln_c99_significant_digits(double value, size_t count, char *mantissa,
                                        int *exponent) {
    unsigned char digits[1200];
    size_t total;
    size_t fractional;
    size_t point;
    size_t first;
    size_t index;
    size_t carry_at;
    total = kiln_c99_exact_digits(value, digits, sizeof digits, &fractional);
    /* `digits` is little-endian, so big-endian position `i` is `digits[total - 1 - i]`, and
     * `point` of those sit above the decimal point. */
    point = total - fractional;
    for (first = 0; first < total && digits[total - 1 - first] == 0; ++first) {
    }
    if (first == total) {
        /* Zero has no significant digit: the specification names its mantissa as zeros and its
         * exponent as zero. */
        for (index = 0; index < count; ++index) {
            mantissa[index] = '0';
        }
        mantissa[count] = '\0';
        *exponent = 0;
        return;
    }
    /* The digit at `first` sits in the place worth 10^(point - 1 - first). */
    *exponent = (int)point - 1 - (int)first;
    for (index = 0; index < count; ++index) {
        size_t at = first + index;
        mantissa[index] = at < total ? (char)('0' + digits[total - 1 - at]) : '0';
    }
    mantissa[count] = '\0';
    /* Only the deciding digit is consulted: at or above five the answer rounds up whatever
     * follows it. A place past the end of the exact expansion is a zero and decides nothing. */
    if (first + count < total && digits[total - 1 - (first + count)] >= 5) {
        carry_at = count;
        for (;;) {
            if (carry_at == 0) {
                /* The carry ran off the front: every digit was a nine, so the mantissa is a one
                 * followed by zeros and the exponent moved up one. */
                mantissa[0] = '1';
                for (index = 1; index < count; ++index) {
                    mantissa[index] = '0';
                }
                *exponent += 1;
                break;
            }
            carry_at -= 1;
            if (mantissa[carry_at] == '9') {
                mantissa[carry_at] = '0';
                continue;
            }
            mantissa[carry_at] += 1;
            break;
        }
    }
}

/* The *shortest* mantissa and decimal exponent that name a finite non-negative value exactly,
 * which is what `toExponential` with no argument asks for.
 *
 * Read off the number provider's own shortest spelling rather than decided again here. That
 * spelling is already the fewest digits that round-trip (ADR 0018), so reading it is the only
 * way `(1234.5678).toExponential()` and `String(1234.5678)` cannot come to disagree about how
 * many digits the value needs. */
static int kiln_c99_shortest_digits(double value, char *mantissa, size_t capacity, int *exponent) {
    kiln_value spelled = kiln_c99_text(kiln_c99_number(value));
    const kiln_string *spelling;
    size_t len;
    size_t body;
    size_t index;
    size_t produced = 0;
    size_t point;
    size_t first;
    size_t last;
    char raw[64];
    int suffix = 0;
    int suffix_sign = 1;
    if (spelled.tag != KILN_VALUE_STRING || spelled.ptr == NULL) {
        return KILN_C99_OUT_OF_MEMORY;
    }
    /* The value's pointer names the header, not the spelling: indexing it as
     * bytes reads the length and flags words as digits. */
    spelling = (const kiln_string *)spelled.ptr;
    len = spelling->unit_len;
    /* `1e+21` and above, and `1e-7` and below, are spelled with an exponent already; everything
     * between is spelled positionally. Both forms reduce to the same digits-and-a-place. */
    body = len;
    for (index = 0; index < len; ++index) {
        uint32_t unit = kiln_string_unit_at(spelling, index);
        if (unit == 'e' || unit == 'E') {
            size_t at = index + 1;
            body = index;
            if (at < len) {
                uint32_t sign = kiln_string_unit_at(spelling, at);
                if (sign == '+' || sign == '-') {
                    suffix_sign = sign == '-' ? -1 : 1;
                    at += 1;
                }
            }
            for (; at < len; ++at) {
                uint32_t digit = kiln_string_unit_at(spelling, at);
                if (digit < '0' || digit > '9') {
                    break;
                }
                suffix = suffix * 10 + (int)(digit - '0');
            }
            suffix *= suffix_sign;
            break;
        }
    }
    point = (size_t)-1;
    for (index = 0; index < body && produced < sizeof raw; ++index) {
        uint32_t unit = kiln_string_unit_at(spelling, index);
        if (unit == '.') {
            point = produced;
            continue;
        }
        if (unit < '0' || unit > '9') {
            /* A sign; the caller asked about a magnitude. */
            continue;
        }
        raw[produced++] = (char)unit;
    }
    if (point == (size_t)-1) {
        point = produced;
    }
    for (first = 0; first < produced && raw[first] == '0'; ++first) {
    }
    if (first == produced) {
        if (capacity < 2) {
            return KILN_C99_OUT_OF_MEMORY;
        }
        mantissa[0] = '0';
        mantissa[1] = '\0';
        *exponent = 0;
        return KILN_C99_OK;
    }
    /* Trailing zeros are place-holding, not significant: `100` is `1e+2`, not `100e+0`. */
    for (last = produced; last > first + 1 && raw[last - 1] == '0'; --last) {
    }
    if (last - first + 1 > capacity) {
        return KILN_C99_OUT_OF_MEMORY;
    }
    for (index = first; index < last; ++index) {
        mantissa[index - first] = raw[index];
    }
    mantissa[last - first] = '\0';
    *exponent = (int)point - 1 - (int)first + suffix;
    return KILN_C99_OK;
}

/* One mantissa and exponent as both exponential formats write them: `1.25e+2`. */
static int kiln_c99_exponential_text(kiln_value *out, int negative, const char *mantissa,
                                     int exponent) {
    kiln_text text = {NULL, 0, 0};
    char rendered[16];
    size_t length = strlen(mantissa);
    unsigned magnitude = exponent < 0 ? (unsigned)-(long)exponent : (unsigned)exponent;
    size_t at = sizeof rendered;
    int failed = 0;
    if (negative) {
        failed = failed || kiln_c99_text_append_c(&text, "-") != KILN_C99_OK;
    }
    failed = failed || kiln_c99_text_append(&text, mantissa, 1) != KILN_C99_OK;
    if (length > 1) {
        failed = failed || kiln_c99_text_append_c(&text, ".") != KILN_C99_OK;
        failed = failed || kiln_c99_text_append(&text, mantissa + 1, length - 1) != KILN_C99_OK;
    }
    failed = failed || kiln_c99_text_append_c(&text, "e") != KILN_C99_OK;
    /* The sign is always written, which is the whole difference from `String(n)`'s own
     * exponential form for a positive exponent. */
    failed = failed || kiln_c99_text_append_c(&text, exponent < 0 ? "-" : "+") != KILN_C99_OK;
    do {
        rendered[--at] = (char)('0' + magnitude % 10u);
        magnitude /= 10u;
    } while (magnitude != 0 && at > 0);
    failed = failed ||
             kiln_c99_text_append(&text, rendered + at, sizeof rendered - at) != KILN_C99_OK;
    if (failed) {
        free(text.bytes);
        return KILN_C99_OUT_OF_MEMORY;
    }
    /* The builder holds malloc'd bytes; a string value carries a headed unit string. The
     * escape copies through the canonical conversion and frees the builder. */
    *out = kiln_c99_text_value(&text);
    return KILN_C99_OK;
}

/* `toPrecision`'s positional form, and its own window for when to give up on one.
 *
 * The switch to the exponential form is the specification's, and it is what keeps
 * `(0.0000001).toPrecision(2)` from being a string of zeros with no digits in it. */
static int kiln_c99_precision_text(kiln_value *out, int negative, const char *mantissa,
                                   size_t digits, int exponent) {
    kiln_text text = {NULL, 0, 0};
    size_t length = strlen(mantissa);
    size_t split;
    int index;
    int failed = 0;
    if (exponent < -6 || exponent >= (int)digits) {
        return kiln_c99_exponential_text(out, negative, mantissa, exponent);
    }
    if (negative) {
        failed = failed || kiln_c99_text_append_c(&text, "-") != KILN_C99_OK;
    }
    if (exponent == (int)digits - 1) {
        /* Every significant digit is above the point, so there is no point. */
        failed = failed || kiln_c99_text_append(&text, mantissa, length) != KILN_C99_OK;
    } else if (exponent >= 0) {
        split = (size_t)exponent + 1;
        failed = failed || kiln_c99_text_append(&text, mantissa, split) != KILN_C99_OK;
        failed = failed || kiln_c99_text_append_c(&text, ".") != KILN_C99_OK;
        failed = failed ||
                 kiln_c99_text_append(&text, mantissa + split, length - split) != KILN_C99_OK;
    } else {
        failed = failed || kiln_c99_text_append_c(&text, "0.") != KILN_C99_OK;
        for (index = 0; index < -exponent - 1; ++index) {
            failed = failed || kiln_c99_text_append_c(&text, "0") != KILN_C99_OK;
        }
        failed = failed || kiln_c99_text_append(&text, mantissa, length) != KILN_C99_OK;
    }
    if (failed) {
        free(text.bytes);
        return KILN_C99_OUT_OF_MEMORY;
    }
    /* As above: escape through the canonical conversion rather than wrapping malloc'd
     * bytes as a headed value. */
    *out = kiln_c99_text_value(&text);
    return KILN_C99_OK;
}

/* A number written in a base other than ten, which `Number.prototype.toString` is the only way
 * to ask for. Digits are produced by repeated division rather than by the number formatter,
 * because the formatter only knows base ten -- and the fraction is bounded at 52 digits, which is
 * every bit a double has to say. */
static int kiln_c99_number_in_radix(kiln_value *out, double value, int radix) {
    kiln_text text = {NULL, 0, 0};
    static const char alphabet[] = "0123456789abcdefghijklmnopqrstuvwxyz";
    char digits[1120];
    size_t count = 0;
    double whole;
    double fraction;
    int negative;
    if (radix == 10) {
        /* Base ten is `Number::toString`, not this walk: the repeated division below spells the
         * exact expansion of the fraction, where the language wants the shortest decimal that
         * reads back as the same double, and it has no exponential form at all. `(1e21)
         * .toString(10)` is "1e+21". */
        char spelled[32];
        size_t written = kiln_c99_double_to_js(value, spelled);
        *out = kiln_c99_copy_text(spelled, written);
        return out->tag == KILN_VALUE_STRING ? KILN_C99_OK : KILN_C99_OUT_OF_MEMORY;
    }
    if (!isfinite(value)) {
        *out = kiln_c99_text(kiln_c99_number(value));
        return KILN_C99_OK;
    }
    negative = value < 0.0;
    value = fabs(value);
    whole = trunc(value);
    fraction = value - whole;
    while (whole >= 1.0 && count < sizeof digits) {
        digits[count++] = alphabet[(int)fmod(whole, (double)radix)];
        whole = trunc(whole / (double)radix);
    }
    if (negative && kiln_c99_text_append_c(&text, "-") != KILN_C99_OK) {
        free(text.bytes);
        return KILN_C99_OUT_OF_MEMORY;
    }
    if (count == 0 && kiln_c99_text_append_c(&text, "0") != KILN_C99_OK) {
        free(text.bytes);
        return KILN_C99_OUT_OF_MEMORY;
    }
    while (count > 0) {
        count -= 1;
        if (kiln_c99_text_append(&text, digits + count, 1) != KILN_C99_OK) {
            free(text.bytes);
            return KILN_C99_OUT_OF_MEMORY;
        }
    }
    if (fraction > 0.0) {
        int place;
        if (kiln_c99_text_append_c(&text, ".") != KILN_C99_OK) {
            free(text.bytes);
            return KILN_C99_OUT_OF_MEMORY;
        }
        for (place = 0; place < 52 && fraction > 0.0; ++place) {
            double digit;
            char character;
            fraction *= (double)radix;
            digit = trunc(fraction);
            character = alphabet[(int)digit];
            fraction -= digit;
            if (kiln_c99_text_append(&text, &character, 1) != KILN_C99_OK) {
                free(text.bytes);
                return KILN_C99_OUT_OF_MEMORY;
            }
        }
    }
    *out = kiln_c99_text_value(&text);
    return KILN_C99_OK;
}
