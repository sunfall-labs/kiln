#!/usr/bin/env bash
# Vendors the declarations `kiln check` embeds for Node: @types/node and the undici-types package
# it imports, under node_modules/ of the library directory, so that module resolution inside the virtual library
# directory finds `undici-types` the way it would on disk. They are stored as lib/vendor/types-node
# and lib/vendor/undici-types (a directory named node_modules is git-ignored) and published under
# node_modules/ in the library table. Then regenerates src/libraries_node.rs,
# the table of every file there. Needs network and npm.
#
#   tools/vendor_node_types.sh 26.6.5
#
# The @types/node version tracks the Node release kiln targets (README: node 26); undici-types is
# whatever that @types/node release depends on. Both are MIT; their LICENSE files stay beside them.
set -euo pipefail
cd "$(dirname "$0")/.."
version="${1:?usage: vendor_node_types.sh <@types/node version>}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
(cd "$work" && npm pack --silent "@types/node@$version" >/dev/null 2>&1 && mkdir node && tar xzf types-node-*.tgz -C node --strip-components=1)
undici="$(node -e 'console.log(require(process.argv[1]).dependencies["undici-types"].replace(/^[~^]/, ""))' "$work/node/package.json")"
(cd "$work" && npm pack --silent "undici-types@$undici" >/dev/null 2>&1 && mkdir undici && tar xzf undici-types-*.tgz -C undici --strip-components=1)
rm -rf lib/vendor
mkdir -p lib/vendor/types-node lib/vendor/undici-types
# typesVersions redirects (ts5.6/, ts5.7/) are for old compilers; the pinned one reads the root.
rsync -a --exclude 'ts5.*' --exclude README.md "$work/node/" lib/vendor/types-node/
rsync -a --exclude README.md "$work/undici/" lib/vendor/undici-types/
{
	echo "//! Generated by tools/vendor_node_types.sh: @types/node $version and undici-types $undici (MIT)."
	echo "/// Paths relative to the library directory."
	echo "pub const NODE_LIBRARIES: &[(&str, &str)] = &["
	for pair in types-node:@types/node undici-types:undici-types; do
		dir="${pair%%:*}"
		name="${pair#*:}"
		(cd lib/vendor && find "$dir" -type f -name '*.d.ts' | LC_ALL=C sort) | while read -r path; do
			printf '    ("node_modules/%s/%s", include_str!("../lib/vendor/%s")),\n' "$name" "${path#*/}" "$path"
		done
		printf '    ("node_modules/%s/package.json", include_str!("../lib/vendor/%s/package.json")),\n' "$name" "$dir"
	done
	echo "];"
} >src/libraries_node.rs
rustfmt --edition 2024 src/libraries_node.rs
echo "vendored @types/node $version, undici-types $undici"
